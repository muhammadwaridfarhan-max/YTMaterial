package com.example.ytclient.ui

import android.content.Context
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableFloatStateOf
import androidx.compose.runtime.mutableIntStateOf
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import android.net.Uri
import androidx.media3.common.C
import androidx.media3.common.MediaItem
import androidx.media3.common.MimeTypes
import androidx.media3.common.PlaybackException
import androidx.media3.common.Player
import androidx.media3.datasource.DefaultHttpDataSource
import androidx.media3.exoplayer.ExoPlayer
import androidx.media3.exoplayer.hls.HlsMediaSource
import androidx.media3.exoplayer.source.DefaultMediaSourceFactory
import androidx.media3.exoplayer.source.MediaSource
import androidx.media3.exoplayer.source.MergingMediaSource
import androidx.media3.exoplayer.source.ProgressiveMediaSource
import com.example.ytclient.data.AudioOption
import com.example.ytclient.data.Repository
import com.example.ytclient.data.SubtitleOption
import com.example.ytclient.settings.SettingsManager
import com.example.ytclient.data.VideoItem
import com.example.ytclient.data.VideoStreams
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.launch

/**
 * Shared playback state so the player survives navigation between tabs:
 * full-screen player when [expanded] is true, mini player above the nav bar otherwise.
 */
@androidx.annotation.OptIn(androidx.media3.common.util.UnstableApi::class)
class PlayerController(context: Context) {
    val player: ExoPlayer = ExoPlayer.Builder(context).build()

    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Main.immediate)
    private var job: Job? = null

    var current by mutableStateOf<VideoItem?>(null)
        private set
    var streams by mutableStateOf<VideoStreams?>(null)
        private set
    var isLoading by mutableStateOf(false)
        private set
    var isBuffering by mutableStateOf(false)
        private set
    var isPlayingState by mutableStateOf(false)
        private set
    var error by mutableStateOf<String?>(null)
        private set

    /** Selected video height; -1 = Auto (best quality capped at 720p for smooth playback). */
    var qualityHeight by mutableIntStateOf(-1)
        private set

    var expanded by mutableStateOf(false)

    var isFullscreen by mutableStateOf(false)

    /** Playback speed, 1f = normal. */
    var speed by mutableFloatStateOf(1f)
        private set

    @JvmName("changeSpeed")
    fun setSpeed(value: Float) {
        speed = value
        player.setPlaybackSpeed(value)
        scope.launch { runCatching { SettingsManager.setPlayerSpeed(value) } }
    }

    /** Selected audio track id (null = original / only track). */
    var audioTrackId by mutableStateOf<String?>(null)
        private set
    /** Remembered audio language tag ("" = original). */
    private var preferredAudioLang = ""

    /** Selected caption language tag ("" = off) + auto-generated flag + auto-translate target. */
    var subtitleLang by mutableStateOf("")
        private set
    var subtitleAuto by mutableStateOf(false)
        private set
    var subtitleTranslate by mutableStateOf("")
        private set

    /** Sleep timer: wall-clock end in ms (0 = off), or pause at end of the current video. */
    var sleepAtMs by mutableStateOf(0L)
        private set
    var sleepEndOfVideo by mutableStateOf(false)
        private set
    private var sleepJob: Job? = null

    fun setAudioTrack(option: AudioOption?) {
        val s = streams ?: return
        val target = option ?: s.audioTracks.firstOrNull { it.isOriginal } ?: s.audioTracks.firstOrNull()
        preferredAudioLang = if (option == null || option.isOriginal) "" else option.languageTag.orEmpty()
        scope.launch { runCatching { SettingsManager.setAudioLanguage(preferredAudioLang) } }
        if (target?.id == audioTrackId) return
        audioTrackId = target?.id
        applySource(keepPosition = true)
    }

    /** [option] null = subtitles off. [translateTo] "" = no auto-translate. */
    fun setSubtitle(option: SubtitleOption?, translateTo: String = "") {
        subtitleLang = option?.languageTag.orEmpty()
        subtitleAuto = option?.autoGenerated ?: false
        subtitleTranslate = if (option == null) "" else translateTo
        scope.launch { runCatching { SettingsManager.setSubtitle(subtitleLang, subtitleTranslate) } }
        if (streams != null) applySource(keepPosition = true)
    }

    fun canTranslate(option: SubtitleOption): Boolean = option.url.contains("timedtext")

    /** [minutes] 0 = off, -1 = end of current video. */
    fun setSleepTimer(minutes: Int) {
        sleepJob?.cancel()
        sleepAtMs = 0L
        sleepEndOfVideo = minutes == -1
        player.pauseAtEndOfMediaItems = sleepEndOfVideo
        if (minutes > 0) {
            val end = System.currentTimeMillis() + minutes * 60_000L
            sleepAtMs = end
            sleepJob = scope.launch {
                delay(end - System.currentTimeMillis())
                player.pause()
                sleepAtMs = 0L
            }
        }
    }

    private fun currentSubtitle(): SubtitleOption? {
        if (subtitleLang.isEmpty()) return null
        val subs = streams?.subtitles.orEmpty()
        return subs.firstOrNull { it.languageTag == subtitleLang && it.autoGenerated == subtitleAuto }
            ?: subs.firstOrNull { it.languageTag == subtitleLang }
            ?: subs.firstOrNull { it.languageTag.substringBefore('-') == subtitleLang.substringBefore('-') }
    }

    fun seekTo(positionMs: Long) = player.seekTo(positionMs.coerceAtLeast(0L))

    fun seekBy(deltaMs: Long) {
        val dur = player.duration.takeIf { it > 0 } ?: Long.MAX_VALUE
        player.seekTo((player.currentPosition + deltaMs).coerceIn(0L, dur))
    }

    init {
        player.addListener(object : Player.Listener {
            override fun onIsPlayingChanged(isPlaying: Boolean) {
                isPlayingState = isPlaying
            }

            override fun onPlaybackStateChanged(playbackState: Int) {
                isBuffering = playbackState == Player.STATE_BUFFERING
            }

            override fun onPlayWhenReadyChanged(playWhenReady: Boolean, reason: Int) {
                // "End of video" sleep timer is one-shot.
                if (!playWhenReady && reason == Player.PLAY_WHEN_READY_CHANGE_REASON_END_OF_MEDIA_ITEM &&
                    sleepEndOfVideo
                ) {
                    sleepEndOfVideo = false
                    player.pauseAtEndOfMediaItems = false
                }
            }

            override fun onPlayerError(playbackError: PlaybackException) {
                error = playbackError.message
            }
        })
        // Restore remembered speed / audio language / captions.
        scope.launch {
            val prefs = runCatching { SettingsManager.playerPrefs.first() }.getOrNull() ?: return@launch
            preferredAudioLang = prefs.audioLanguage
            subtitleLang = prefs.subtitleLanguage
            subtitleTranslate = prefs.subtitleTranslate
            if (prefs.speed != speed) {
                speed = prefs.speed
                player.setPlaybackSpeed(prefs.speed)
            }
        }
    }

    fun open(item: VideoItem) {
        if (current?.url != item.url) {
            current = item
            qualityHeight = -1
            streams = null
            error = null
            load()
        }
        expanded = true
    }

    fun retry() = load()

    fun setQuality(height: Int) {
        if (qualityHeight == height) return
        qualityHeight = height
        if (streams != null) applySource()
    }

    fun togglePlay() {
        if (player.isPlaying) player.pause() else player.play()
    }

    fun close() {
        job?.cancel()
        player.stop()
        player.clearMediaItems()
        current = null
        streams = null
        error = null
        expanded = false
        isFullscreen = false
    }

    fun release() {
        sleepJob?.cancel()
        scope.cancel()
        player.release()
    }

    private fun load() {
        val item = current ?: return
        job?.cancel()
        job = scope.launch {
            isLoading = true
            error = null
            runCatching { Repository.resolveStreams(item.url) }
                .onSuccess { result ->
                    streams = result
                    audioTrackId = pickAudio(result.audioTracks)?.id
                    applySource()
                }
                .onFailure {
                    isLoading = false
                    error = it.message
                }
        }
    }

    private fun pickAudio(tracks: List<AudioOption>): AudioOption? {
        if (tracks.isEmpty()) return null
        val pref = preferredAudioLang
        if (pref.isNotEmpty()) {
            tracks.firstOrNull { !it.isOriginal && it.languageTag == pref }?.let { return it }
            tracks.firstOrNull {
                !it.isOriginal && it.languageTag?.substringBefore('-') == pref.substringBefore('-')
            }?.let { return it }
        }
        return tracks.firstOrNull { it.isOriginal } ?: tracks.first()
    }

    private fun applySource(keepPosition: Boolean = false) {
        val s = streams ?: return
        val pos = if (keepPosition) player.currentPosition else 0L
        try {
            player.setMediaSource(buildSource(s), pos)
            player.prepare()
            player.playWhenReady = true
            error = null
        } catch (t: Throwable) {
            error = t.message
        } finally {
            isLoading = false
        }
    }

    private fun buildSource(s: VideoStreams): MediaSource {
        val dsf = DefaultHttpDataSource.Factory()
            .setUserAgent(USER_AGENT)
            .setAllowCrossProtocolRedirects(true)

        fun progressive(url: String): MediaSource =
            ProgressiveMediaSource.Factory(dsf).createMediaSource(MediaItem.fromUri(url))

        val sub = currentSubtitle()
        val subConfigs = if (sub == null) emptyList() else {
            var url = sub.url
            if (subtitleTranslate.isNotEmpty() && canTranslate(sub)) {
                url = Uri.parse(url).buildUpon().appendQueryParameter("tlang", subtitleTranslate)
                    .build().toString()
            }
            listOf(
                MediaItem.SubtitleConfiguration.Builder(Uri.parse(url))
                    .setMimeType(MimeTypes.TEXT_VTT)
                    .setLanguage(subtitleTranslate.ifEmpty { sub.languageTag })
                    .setSelectionFlags(C.SELECTION_FLAG_DEFAULT)
                    .build()
            )
        }

        /** Video (or muxed) source, with side-loaded captions merged in when enabled. */
        fun videoSource(url: String): MediaSource =
            if (subConfigs.isEmpty()) progressive(url)
            else DefaultMediaSourceFactory(dsf).createMediaSource(
                MediaItem.Builder().setUri(url).setSubtitleConfigurations(subConfigs).build()
            )

        val audioUrl = s.audioTracks.firstOrNull { it.id == audioTrackId }?.url ?: s.audioUrl

        if (s.isLive && s.hlsUrl != null) {
            return HlsMediaSource.Factory(dsf).createMediaSource(MediaItem.fromUri(s.hlsUrl))
        }

        val cap = if (qualityHeight <= 0) 720 else qualityHeight
        val video = s.videoOnly.firstOrNull { it.height <= cap } ?: s.videoOnly.lastOrNull()
        if (video != null && audioUrl != null) {
            return MergingMediaSource(videoSource(video.url), progressive(audioUrl))
        }

        val progressiveTrack =
            s.progressive.firstOrNull { it.height <= cap } ?: s.progressive.lastOrNull()
        if (progressiveTrack != null) return videoSource(progressiveTrack.url)

        if (s.hlsUrl != null) {
            return HlsMediaSource.Factory(dsf).createMediaSource(MediaItem.fromUri(s.hlsUrl))
        }
        error("No playable stream found")
    }

    companion object {
        private const val USER_AGENT =
            "Mozilla/5.0 (Windows NT 10.0; rv:128.0) Gecko/20100101 Firefox/128.0"
    }
}
